import { isAbsolute, join, relative } from "node:path";
import { pathToFileURL } from "node:url";

import { prepareOutputDirectory, writeOutputFile } from "./output.js";
import { planSourceTests } from "./sourcePlanner.js";
import type {
  GenerateSourceInput,
  GenerateSourceResult,
  GeneratedFile,
  SourceTestCase,
} from "./types.js";

const SOURCE_TEST_FILE_NAME = "tea-source-tests.mjs";
const SOURCE_PLAN_FILE_NAME = "tea-source-plan.json";

/** Generate a standalone node:test file plus tea-source-plan.json into outputDir. */
export const generateSourceTestArtifacts = async (
  input: GenerateSourceInput,
): Promise<GenerateSourceResult> => {
  const plan =
    input.plan ?? (await planSourceTests({ repoDir: input.repoDir }));
  const outputDir = await prepareOutputDirectory(input.outputDir);
  const overwrite = input.overwrite === true;

  const testContent = renderSourceTestFile(outputDir, plan.cases);
  const planContent = `${JSON.stringify(plan, null, 2)}\n`;

  const files: GeneratedFile[] = [];
  const testPath = join(outputDir, SOURCE_TEST_FILE_NAME);
  const planPath = join(outputDir, SOURCE_PLAN_FILE_NAME);
  await writeOutputFile(testPath, testContent, overwrite);
  await writeOutputFile(planPath, planContent, overwrite);
  files.push({ path: testPath, kind: "test" });
  files.push({ path: planPath, kind: "plan" });

  return {
    outputDir,
    files,
    caseCount: plan.cases.length,
    excludedCount: plan.excluded.length,
    limitations: plan.limitations,
  };
};

export const renderSourceTestFile = (
  outputDir: string,
  cases: readonly SourceTestCase[],
): string => {
  const modules: string[] = [];
  const moduleIndex = new Map<string, number>();
  for (const testCase of cases) {
    if (!moduleIndex.has(testCase.sourcePath)) {
      moduleIndex.set(testCase.sourcePath, modules.length);
      modules.push(testCase.sourcePath);
    }
  }
  const importLines = modules.map(
    (sourcePath, index) =>
      `import * as teaMod${index} from ${JSON.stringify(relativeImportSpecifier(outputDir, sourcePath))};`,
  );
  const renderedCases = cases.map((testCase) => ({
    id: testCase.id,
    description: testCase.description,
    module: moduleIndex.get(testCase.sourcePath),
    exportName: testCase.exportName,
    args: testCase.args,
    expected: testCase.expected,
  }));

  return `// Generated by tea-agents. Do not edit; regenerate with generate-source-tests.
import { test } from "node:test";
import assert from "node:assert/strict";

${importLines.join("\n")}

const MODULES = [${modules.map((_, index) => `teaMod${index}`).join(", ")}];
const CASES = ${JSON.stringify(renderedCases)};

function normalize(value) {
  return typeof value === "number" && Object.is(value, -0) ? 0 : value;
}

for (const testCase of CASES) {
  test(testCase.id, () => {
    const fn = MODULES[testCase.module][testCase.exportName];
    assert.strictEqual(
      typeof fn,
      "function",
      testCase.exportName + " should be a function",
    );
    assert.strictEqual(
      normalize(fn(...testCase.args)),
      testCase.expected,
      testCase.description,
    );
  });
}
`;
};

/**
 * Build an ESM import specifier from the output directory to a source file.
 * When the two live on different drives/roots, `relative` yields an absolute
 * path that cannot be imported relatively, so emit a file URL instead.
 */
const relativeImportSpecifier = (
  outputDir: string,
  sourcePath: string,
): string => {
  const resolved = relative(outputDir, sourcePath);
  if (isAbsolute(resolved)) return pathToFileURL(resolved).href;
  let specifier = resolved.replace(/\\/gu, "/");
  if (!specifier.startsWith(".")) specifier = `./${specifier}`;
  return specifier;
};
