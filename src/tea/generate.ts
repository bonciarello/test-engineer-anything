import { lstat, mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

import { parseSpecDocument } from "./specs.js";
import { planContractTests } from "./plan.js";
import { VALIDATOR_CODE } from "./validatorTemplate.js";
import type {
  GenerateInput,
  GenerateTestsResult,
  GeneratedFile,
  JsonValue,
} from "./types.js";
import { TeaError } from "./types.js";

const TEST_FILE_NAME = "tea-contract-tests.mjs";
const PLAN_FILE_NAME = "tea-plan.json";

/** Generate a standalone node:test file plus tea-plan.json into outputDir. */
export const generateTestArtifacts = async (
  input: GenerateInput,
): Promise<GenerateTestsResult> => {
  const plan =
    input.plan ?? (await planContractTests({ repoDir: input.repoDir }));
  const outputDir = await prepareOutputDirectory(input.outputDir);
  const overwrite = input.overwrite === true;

  const docs: JsonValue[] = [];
  const docIndex = new Map<string, number>();
  for (const specPath of plan.specs) {
    const parsed = parseSpecDocument(await readFile(specPath, "utf8"));
    if (parsed.kind !== "openapi3") continue;
    docIndex.set(specPath, docs.length);
    docs.push(parsed.document);
  }

  const cases = plan.cases.map((testCase) => {
    const doc = docIndex.get(testCase.evidence.specPath);
    if (doc === undefined)
      throw new TeaError(
        "internal",
        `spec ${testCase.evidence.specPath} is missing from the generated document set`,
      );
    return {
      id: testCase.id,
      method: testCase.method.toUpperCase(),
      path: testCase.pathTemplate,
      pathParams: testCase.pathParams,
      queryParams: testCase.queryParams,
      expectedStatus: testCase.expectedStatus,
      any2xx: testCase.any2xx,
      responses: testCase.responses.map((response) => ({
        status: response.status,
        jsonContentType: response.jsonContentType,
        schemaPointer: response.schemaPointer,
        schemaSupported: response.schemaSupported,
      })),
      doc,
    };
  });

  const testContent = renderTestFile(docs, cases);
  const planContent = `${JSON.stringify(plan, null, 2)}\n`;

  const files: GeneratedFile[] = [];
  const testPath = join(outputDir, TEST_FILE_NAME);
  const planPath = join(outputDir, PLAN_FILE_NAME);
  await writeOutputFile(testPath, testContent, overwrite);
  await writeOutputFile(planPath, planContent, overwrite);
  files.push({ path: testPath, kind: "test" });
  files.push({ path: planPath, kind: "plan" });

  return {
    outputDir,
    files,
    caseCount: cases.length,
    excludedCount: plan.excluded.length,
    limitations: plan.limitations,
  };
};

/**
 * Prepare an output directory without following a symlinked directory or
 * writing through a symlinked file. Creates the directory when missing.
 */
const prepareOutputDirectory = async (outputDir: string): Promise<string> => {
  if (typeof outputDir !== "string" || outputDir.trim() === "")
    throw new TeaError("invalid_input", "outputDir must be a non-empty path");
  const resolved = resolve(outputDir);
  try {
    await mkdir(resolved, { recursive: true });
  } catch {
    throw new TeaError(
      "invalid_output",
      `cannot create output directory: ${resolved}`,
    );
  }
  const info = await lstat(resolved);
  if (info.isSymbolicLink())
    throw new TeaError("unsafe_output", "output directory is a symlink");
  if (!info.isDirectory())
    throw new TeaError("invalid_output", "outputDir is not a directory");
  return resolved;
};

/** Write a file, refusing to overwrite without consent or follow a symlink. */
const writeOutputFile = async (
  targetPath: string,
  content: string,
  overwrite: boolean,
): Promise<void> => {
  try {
    const info = await lstat(targetPath);
    if (info.isSymbolicLink())
      throw new TeaError(
        "unsafe_output",
        `refusing to write through a symlink: ${targetPath}`,
      );
    if (!overwrite)
      throw new TeaError(
        "already_exists",
        `output file already exists (pass overwrite to replace it): ${targetPath}`,
      );
  } catch (cause) {
    if (cause instanceof TeaError) throw cause;
    if (!isMissing(cause)) throw cause;
  }
  await writeFile(targetPath, content, { flag: overwrite ? "w" : "wx" });
};

const renderTestFile = (docs: JsonValue[], cases: unknown[]): string =>
  `// Generated by tea-agents. Do not edit; regenerate with generate-tests.
import { test } from "node:test";
import assert from "node:assert/strict";

const BASE_URL = process.env.TEA_BASE_URL;
if (typeof BASE_URL !== "string" || BASE_URL === "") {
  throw new Error("TEA_BASE_URL environment variable is required");
}

const DOCS = ${JSON.stringify(docs)};
const CASES = ${JSON.stringify(cases)};

${VALIDATOR_CODE}

function buildUrl(baseUrl, pathTemplate, pathParams, queryParams) {
  let path = "";
  let index = 0;
  while (index < pathTemplate.length) {
    const char = pathTemplate[index];
    if (char === "{") {
      const end = pathTemplate.indexOf("}", index + 1);
      if (end === -1)
        throw new Error("unterminated path parameter in " + pathTemplate);
      const name = pathTemplate.slice(index + 1, end);
      const value = pathParams[name];
      if (value === undefined)
        throw new Error("missing path parameter value for " + name);
      path += encodeURIComponent(value);
      index = end + 1;
    } else {
      path += char;
      index += 1;
    }
  }
  let base = baseUrl;
  while (base.length > 1 && base.endsWith("/")) base = base.slice(0, -1);
  let url = base + path;
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(queryParams)) query.set(key, value);
  const queryString = query.toString();
  if (queryString !== "") url = url + "?" + queryString;
  return url;
}

for (const testCase of CASES) {
  test(testCase.id, async () => {
    const doc = DOCS[testCase.doc];
    const url = buildUrl(
      BASE_URL,
      testCase.path,
      testCase.pathParams,
      testCase.queryParams,
    );
    const response = await fetch(url, { method: testCase.method });
    if (testCase.any2xx) {
      assert.ok(
        response.status >= 200 && response.status < 300,
        "expected a 2xx status, got " + response.status + " for " + url,
      );
    } else {
      assert.ok(
        testCase.expectedStatus.includes(response.status),
        "expected status " +
          JSON.stringify(testCase.expectedStatus) +
          ", got " +
          response.status +
          " for " +
          url,
      );
    }
    const assertion = testCase.any2xx
      ? testCase.responses.find((entry) => entry.status === null)
      : testCase.responses.find((entry) => entry.status === response.status);
    if (assertion === undefined) return;
    if (assertion.jsonContentType) {
      const contentType = response.headers.get("content-type") ?? "";
      assert.ok(
        contentType.toLowerCase().includes("json"),
        "expected a JSON content-type, got " + JSON.stringify(contentType),
      );
    }
    if (testCase.method === "HEAD") return;
    if (assertion.schemaSupported && assertion.schemaPointer !== null) {
      const text = await response.text();
      let body;
      try {
        body = JSON.parse(text);
      } catch (cause) {
        assert.fail("response body is not valid JSON: " + cause.message);
      }
      validateResponse(doc, assertion.schemaPointer, body);
    }
  });
}
`;

const isMissing = (cause: unknown): boolean =>
  typeof cause === "object" &&
  cause !== null &&
  "code" in cause &&
  (cause as { code?: unknown }).code === "ENOENT";
